// Compile selected frames from the user's local SGQ sheets into game-ready 2bpp.
// No source sheets are copied into the repository. Run explicitly after art changes.
import fs from 'node:fs';import path from 'node:path';import {fileURLToPath} from 'node:url';import {decodePng} from './assets.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const library=process.argv[2] || 'G:/My Drive/Artwork/Assets/SGQ_Enemies';
const specs=[['normal/16x16/slime.png',16,16,[[0,0],[2,2]]],['normal/32x32/medium_slime.png',32,32,[[0,0],[2,2]]],['bosses/slime_king.png',48,64,[[0,0],[2,2],[2,4]]]];
const data=[],parts=[],starts=[],counts=[];
for(const [file,w,h,frames] of specs){
 const im=decodePng(fs.readFileSync(path.join(library,file)));
 for(const [fx,fy] of frames){starts.push(parts.length);let count=0;
  for(let y=0;y<h;y+=16)for(let x=0;x<w;x+=8){const bytes=[];let opaque=false;
   for(let yy=0;yy<16;yy++){let lo=0,hi=0;for(let xx=0;xx<8;xx++){
    const i=((fy*h+y+yy)*im.width+fx*w+x+xx)*4;
    const c=!im.rgba[i+3]?0:im.rgba[i]>180?1:im.rgba[i+1]>100?2:3;
    opaque ||= c!==0;lo=lo*2+(c&1);hi=hi*2+(c>>1);
   }bytes.push(lo,hi);}
   if(opaque){parts.push([x-w/2,y-h,96+data.length/16]);data.push(...bytes);count++;}
  }counts.push(count);
 }
}
if(96+data.length/16>256)throw new Error('Slime art exceeds sprite VRAM');
let out='// Generated by tools/slime-art.mjs from the local SGQ_Enemies sheets.\n';
out+='static const uint8_t glob_art[] = {\n'+Array.from({length:Math.ceil(data.length/16)},(_,i)=>' '+data.slice(i*16,i*16+16).join(',')).join(',\n')+'\n};\n';
out+='static const int16_t glob_parts[][3] = {\n'+parts.map(p=>' {'+p.join(',')+'}').join(',\n')+'\n};\n';
out+='static const uint8_t glob_first[]={'+starts.join(',')+'};\nstatic const uint8_t glob_count[]={'+counts.join(',')+'};\n';
fs.writeFileSync(path.join(root,'src/globfather_art.inc'),out);console.log(`${data.length/16} tiles; parts per pose: ${counts}`);
