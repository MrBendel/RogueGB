// Skills: content/skills/*.json -> build/gen/skilldata.c + skilldata.h, the
// classes and their skill trees (docs/design/skill-trees.md) for src/skills.c
// and the pause menu (src/menu.c). Called by tools/build.mjs; also runnable on
// its own: node tools/skills.mjs
//
// Each class has 3 branches of 3 skills (tiers). Texts are wrapped here, with the
// compact font's real widths, into at most 2 lines that fit the menu.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GEN_DIR, decodePng } from './assets.mjs';
import { FONTS, sliceFont } from './fonts.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'content', 'skills');
const SHEET = path.join(ROOT, 'artwork', 'fonts', 'font-sheet.png');

export const TEXT_PX = 148;   // a text line in the menu (inside its frame)
export const LINE_CHARS = 40; // bytes kept for a line
const NAME_MAX = 16, SHORT_MAX = 14, BRANCH_MAX = 10;
const LABEL_PX = 46;  // a skill's label in the menu's grid (3 columns): 'short', or its first word
// What the game does with a skill (src/skills.c: SKILL_FX_*); others are planned.
export const EFFECTS = ['hp15', 'shield_fast', 'reload_half', 'shot_speed', 'mag2', 'dash_far', 'fire_fast', 'pellet', 'no_slow', 'aim_far'];

let compact = null;
function measure() {
  if (compact) return compact;
  const f = FONTS.find((x) => x.name === 'compact');
  const { chars, glyphs } = sliceFont(decodePng(fs.readFileSync(SHEET)), f);
  compact = {
    has: (ch) => ch === ' ' || chars.has(ch),
    width: (s) => [...s].reduce((w, ch) => w + (ch === ' ' ? f.space : glyphs[chars.get(ch)].w + f.gap), 0),
  };
  return compact;
}

/** Wrap s into lines of at most `px` (compact font); throws if it needs more than `max`. */
export function wrapCompact(s, px, max, where) {
  const m = measure();
  for (const ch of s) if (!m.has(ch)) throw new Error(`${where}: the compact font has no '${ch}'`);
  const lines = [];
  let line = '';
  for (const word of s.split(/ +/)) {
    const next = line ? `${line} ${word}` : word;
    if (m.width(next) <= px) line = next;
    else { lines.push(line); line = word; }
  }
  lines.push(line);
  if (lines.length > max) throw new Error(`${where}: "${s}" takes ${lines.length} lines (at most ${max})`);
  while (lines.length < max) lines.push('');
  return lines;
}

export function loadSkills() {
  const classes = [];
  for (const f of fs.readdirSync(SRC_DIR).filter((x) => x.endsWith('.json')).sort()) {
    const doc = JSON.parse(fs.readFileSync(path.join(SRC_DIR, f), 'utf8'));
    for (const c of doc.classes) {
      const where = `content/skills/${f}, ${c.key}`;
      if (c.name.length > SHORT_MAX) throw new Error(`${where}: name longer than ${SHORT_MAX}`);
      if (c.branches?.length !== 3 || c.branches.some((b) => b.skills?.length !== 3)) throw new Error(`${where}: needs 3 branches of 3 skills`);
      classes.push({
        key: c.key, name: c.name, role: c.role,
        about: wrapCompact(c.about, TEXT_PX, 2, where),
        branches: c.branches.map((b) => {
          if (b.name.length > BRANCH_MAX) throw new Error(`${where}: branch ${b.name} longer than ${BRANCH_MAX}`);
          return b.name;
        }),
        // Skill k = branch * 3 + tier.
        skills: c.branches.flatMap((b) => b.skills.map((s) => {
          const w = `${where}, ${s.name}`;
          if (s.name.length > NAME_MAX) throw new Error(`${w}: name longer than ${NAME_MAX}`);
          if (s.effect && !EFFECTS.includes(s.effect)) throw new Error(`${w}: effect is one of ${EFFECTS.join(', ')}`);
          const text = s.effect ? s.text : `${s.text} (Not in yet.)`;
          const label = s.short || s.name.split(' ')[0];
          if (measure().width(label) > LABEL_PX) throw new Error(`${w}: label "${label}" is too wide for the grid: give it a "short"`);
          return { name: s.name, label, lines: wrapCompact(text, TEXT_PX, 2, w), effect: s.effect ? EFFECTS.indexOf(s.effect) + 1 : 0 };
        })),
      });
    }
  }
  if (!classes.length || classes.length > 8) throw new Error('content/skills: 1-8 classes');
  return classes;
}

export function buildSkills({ quiet = false } = {}) {
  fs.mkdirSync(GEN_DIR, { recursive: true });
  const c = path.join(GEN_DIR, 'skilldata.c'), h = path.join(GEN_DIR, 'skilldata.h');
  const inputs = [fileURLToPath(import.meta.url), SHEET, ...fs.readdirSync(SRC_DIR).map((f) => path.join(SRC_DIR, f))];
  const newest = Math.max(...inputs.map((f) => fs.statSync(f).mtimeMs));
  if (fs.existsSync(c) && fs.existsSync(h) && fs.statSync(c).mtimeMs > newest) return c;
  const classes = loadSkills();
  const str = (s) => JSON.stringify(s);
  fs.writeFileSync(h, [
    '// Generated by tools/skills.mjs from content/skills/*.json. Do not edit.',
    '#ifndef GEN_SKILLDATA_H', '#define GEN_SKILLDATA_H', '#include <stdint.h>', '#include <gb/gb.h>',
    'BANKREF_EXTERN(skilldata)',
    `#define CLASS_COUNT ${classes.length}`,
    ...classes.map((k, i) => `#define CLASS_${k.key.toUpperCase()} ${i}`),
    '#define SKILLS_PER_CLASS 9  // branch * 3 + tier',
    `#define SKILL_NAME_MAX ${NAME_MAX}`, `#define SKILL_LINE_MAX ${LINE_CHARS}`, `#define CLASS_NAME_MAX ${SHORT_MAX}`,
    `#define BRANCH_NAME_MAX ${BRANCH_MAX}`, '#define CLASS_ROLE_MAX 24',
    ...EFFECTS.map((e, i) => `#define SKILL_FX_${e.toUpperCase()} ${i + 1}`),
    'extern const char class_name[CLASS_COUNT][CLASS_NAME_MAX + 1];',
    'extern const char class_role[CLASS_COUNT][CLASS_ROLE_MAX + 1];',
    'extern const char class_about[CLASS_COUNT][2][SKILL_LINE_MAX + 1];',
    'extern const char branch_name[CLASS_COUNT][3][BRANCH_NAME_MAX + 1];',
    'extern const char skill_name[CLASS_COUNT][SKILLS_PER_CLASS][SKILL_NAME_MAX + 1];',
    'extern const char skill_text[CLASS_COUNT][SKILLS_PER_CLASS][2][SKILL_LINE_MAX + 1];',
    'extern const char skill_label[CLASS_COUNT][SKILLS_PER_CLASS][SKILL_NAME_MAX + 1];  // for the grid',
    'extern const uint8_t skill_effect[CLASS_COUNT][SKILLS_PER_CLASS];  // SKILL_FX_*, or 0',
    '#endif', '',
  ].join('\n'));
  fs.writeFileSync(c, [
    '#pragma bank 255',
    '// Generated by tools/skills.mjs from content/skills/*.json. Do not edit.',
    '#include <gb/gb.h>', '#include "skilldata.h"', 'BANKREF(skilldata)',
    `const char class_name[CLASS_COUNT][CLASS_NAME_MAX + 1] = {${classes.map((k) => str(k.name)).join(', ')}};`,
    `const char class_role[CLASS_COUNT][CLASS_ROLE_MAX + 1] = {${classes.map((k) => str(k.role)).join(', ')}};`,
    `const char class_about[CLASS_COUNT][2][SKILL_LINE_MAX + 1] = {${classes.map((k) => `{${k.about.map(str).join(', ')}}`).join(', ')}};`,
    `const char branch_name[CLASS_COUNT][3][BRANCH_NAME_MAX + 1] = {${classes.map((k) => `{${k.branches.map(str).join(', ')}}`).join(', ')}};`,
    `const char skill_name[CLASS_COUNT][SKILLS_PER_CLASS][SKILL_NAME_MAX + 1] = {${classes.map((k) => `{${k.skills.map((s) => str(s.name)).join(', ')}}`).join(',\n    ')}};`,
    `const char skill_text[CLASS_COUNT][SKILLS_PER_CLASS][2][SKILL_LINE_MAX + 1] = {${classes.map((k) => `{${k.skills.map((s) => `{${s.lines.map(str).join(', ')}}`).join(', ')}}`).join(',\n    ')}};`,
    `const char skill_label[CLASS_COUNT][SKILLS_PER_CLASS][SKILL_NAME_MAX + 1] = {${classes.map((k) => `{${k.skills.map((s) => str(s.label)).join(', ')}}`).join(',\n    ')}};`,
    `const uint8_t skill_effect[CLASS_COUNT][SKILLS_PER_CLASS] = {${classes.map((k) => `{${k.skills.map((s) => s.effect).join(', ')}}`).join(', ')}};`,
    '',
  ].join('\n'));
  if (!quiet) console.log(`[skills] content/skills -> build/gen/skilldata.c (${classes.length} classes)`);
  return c;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const k of loadSkills()) {
    console.log(`== ${k.name} (${k.role}): ${k.about.join(' / ')}`);
    k.skills.forEach((s, i) => console.log(`  ${k.branches[(i / 3) | 0].padEnd(10)} ${s.name.padEnd(16)} ${s.effect ? '*' : ' '} ${s.lines.join(' / ')}`));
  }
  buildSkills();
}
