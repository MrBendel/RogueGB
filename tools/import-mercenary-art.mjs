// Encode the supplied 2x NPC sheet into native 16x16 GBC frames.
// No redraw or color substitution: background -> transparent, other colors -> 1..3.
import fs from 'node:fs';
import {decodePng} from './assets.mjs';
const root=new URL('../',import.meta.url);
const p=decodePng(fs.readFileSync(new URL('artwork/mercenary/source-sheet.png',root)));
if(p.width!==128 || p.height!==768)throw new Error('Expected 128x768 NPC sheet');
const colors=new Map([['216,223,208',0],['255,255,224',1],['24,216,255',2],['16,24,72',3]]);
const out=[];
// Four walk frames down/up/right, then four roll frames down/up/right.
// Left uses hardware mirroring, as on the player.
for(const row of [4,5,6,12,13,14])for(let frame=0;frame<4;frame++)
 for(let col=0;col<2;col++)for(let y=0;y<16;y++){
  let lo=0,hi=0;
  for(let x=0;x<8;x++){
   const xx=(frame*16+col*8+x)*2,yy=(row*16+y)*2;
   const i=(yy*p.width+xx)*4;
   const c=colors.get([...p.rgba.slice(i,i+3)].join(','));
   if(c===undefined)throw new Error('Unexpected sheet color');
   lo=(lo<<1)|(c&1);hi=(hi<<1)|(c>>1);
  }
  out.push(lo,hi);
 }
let text='// Generated by tools/import-mercenary-art.mjs from the supplied NPC sheet.\n';
text+='static const uint8_t mercenary_tiles[] = {\n';
for(let i=0;i<out.length;i+=16)text+=' '+out.slice(i,i+16).join(',')+',\n';
text+='};\n';
fs.writeFileSync(new URL('src/mercenary_art.h',root),text);
