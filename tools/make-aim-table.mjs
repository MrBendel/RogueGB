// Writes src/aim_dir_table.h: the lookup auto-aim uses to turn a direction
// (dx, dy) into one of 32 steps without multiplying (see direction() in aim.c).
//   node tools/make-aim-table.mjs
//
// With the larger of |dx|, |dy| scaled to 16-31 ("hi") and the smaller scaled
// the same way ("lo", 0-31), the entry at (hi - 16) * 32 + lo is k, the number of
// 11.25-degree steps from the nearer axis: how many of tan((k + 0.5) * 11.25 deg)
// = 25, 78, 137, 210 (/256) have lo * 256 >= hi * t.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TAN = [25, 78, 137, 210];
const rows = [];
for (let hi = 16; hi < 32; hi++) {
  const row = [];
  for (let lo = 0; lo < 32; lo++) row.push(TAN.filter((t) => Math.min(lo, hi) * 256 >= hi * t).length);
  rows.push('    ' + row.join(','));
}
fs.writeFileSync(path.join(ROOT, 'src', 'aim_dir_table.h'), `// Generated by tools/make-aim-table.mjs. Do not edit; see that file.
#ifndef AIM_DIR_TABLE_H
#define AIM_DIR_TABLE_H
#include <stdint.h>
static const uint8_t aim_dir_k[16 * 32] = {
${rows.join(',\n')}
};
#endif
`);
console.log('[aim-table] src/aim_dir_table.h');
